/** 兜底符号（未知 / 缺 cover 字段时用；仍是可辨的轮廓，不是空白） */
export const FALLBACK_GLYPH: GlyphId = 'stack';

/**
 * 逐篇覆盖表：**只为一件事存在** —— 两篇文章共用同一个 emoji，但值得不同的符号。
 *
 * 当前唯一一条：🧭 同时挂在「RPA 运行时选型」和「元素捕获偏移」上。
 * 若两篇共用符号，靠第 15 行版本跳线区分，实测两图只差 1 个焊盘（2 格 / 256 格 ≈ 0.8% 像素）——
 * 对列表里相邻的两张卡就是「几乎同一张图」。故这里把「基准 vs 偏移」那篇显式指到 `offset`，
 * 让 18 篇文章拿到 18 个不同轮廓（跨 13 套主题的可辨性由此兜住）。
 * 加新文章时：emoji 撞车 + 两篇都值得自己的形状 → 在这里加一行（覆盖优先于 emoji 表）。
 */
export const GLYPH_BY_ID: Record<string, GlyphId> = {
  '2026-09-08-element-capture-offset': 'offset',
};

/** emoji 归一化：去掉变体选择符 U+FE0F（'🛠️' 与 '🛠' 必须命中同一项） */
function normalizeEmoji(cover: string | undefined): string {
  return (cover ?? '').replace(/\uFE0F/g, '');
}

/**
 * 文章 → 符号（覆盖表 > emoji 表 > 兜底）。
 *
 * @param source.id 文章 slug（= post.id）
 * @param source.cover frontmatter 的 cover emoji（可选）
 */
export function glyphForCover(source: { id?: string; cover?: string }): GlyphId {
  const override = GLYPH_BY_ID[source.id ?? ''];
  if (override) return override;
  return GLYPH_BY_EMOJI[normalizeEmoji(source.cover)] ?? FALLBACK_GLYPH;
}
