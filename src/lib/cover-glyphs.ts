/**
 * 封面符号库（cover glyphs）—— 候选①「轮廓 / 剪影型」的手工像素符号表。
 *
 * 为什么是符号表而不是哈希噪点（调研 `%TEMP%\8bitme-roadmap3\cover-research.md`）：
 *   1. 「随机噪声不可记」（Arne Niklas Jansson, Art Tutorial 原话：Random noise isn't memorable）；
 *      本站旧的 identicon 式镜像噪点 = 差异大 + 无形状 = 「二维码墙」。
 *   2. 小尺寸可辨识度靠**剪影**：每条符号 = 单一主形 + 2 格粗笔画，96px 下笔画 11px（不糊）。
 *   3. 「一套感」不来自图形多样，而来自**统一家具**：同 14×13 芯、同上/左 1 格留白、
 *      同 1 行空白 + 第 15 行版本跳线、每条恰好 1 处强调焦点（≤4 格，**只做点缀，不承载身份**——
 *      --c-accent 在 7/13 主题里与 --c-text 近单色，靠颜色区分会在那些主题里退化成同一张图）。
 *
 * 表格格式（每条 13 行 × 14 字符，字符集只有三种）：
 *   '.' 空 / '#' 浅墨（--c-text）/ '+' 强调（--c-accent）
 * 落在矩阵里时整体 +1 偏移（芯片占 1..14 列 / 1..13 行），四周 1 格留白由 `glyphCover` 守。
 *
 * 纯数据 + 纯函数，零依赖、零 Math.random / Date（构建期 SSR 必须逐格可复现）。
 */

