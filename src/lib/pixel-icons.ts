export interface IconRun {
  x: number;
  y: number;
  w: number;
}

/**
 * 行程合并：每行连续 `#` 合并为一个 run（x 从 0 起，整数格）。
 * 同名图标恒得同输出（构建期确定性，禁 Math.random/Date）。
 */
export function iconRuns(name: IconName): IconRun[] {
  const rows = PIXEL_ICONS[name];
  const runs: IconRun[] = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === '#') {
        let w = 1;
        while (row[x + w] === '#') w++;
        runs.push({ x, y, w });
        x += w;
      } else x++;
    }
  });
  return runs;
}

/** 实心格数（runs 宽度之和，用于与逐格计数互证） */
export function iconFilledCount(name: IconName): number {
  return iconRuns(name).reduce((sum, r) => sum + r.w, 0);
}

/**
 * 内联 SVG 片段（不含 <svg> 外壳）：行程合并 rect，fill 由调用方传
 * （组件传 `var(--c-accent)` 随主题）。整数格 + crispEdges 由外壳负责。
 */
export function iconSvgInner(name: IconName, fill: string): string {
  return iconRuns(name)
    .map((r) => `<rect x="${r.x}" y="${r.y}" width="${r.w}" height="1" fill="${fill}"/>`)
    .join('');
}

